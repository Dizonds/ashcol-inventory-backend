import { frontendBuild, artifactsDirectory } from "./environment.js";
// Full UI/API regression pass against a disposable replica set. Never loads .env.
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import express from "express";
import mongoose from "mongoose";
import { chromium } from "playwright-core";
import { MongoMemoryReplSet } from "mongodb-memory-server";
import app from "../../src/app.js";
import { initializeDatabase } from "../../src/database/setup.js";
import { hashPassword } from "../../src/security/auth.js";
import { User, Supplier, Product, Movement, ServiceVan } from "../../src/database/models.js";

let database, server, browser, page;
const checks = [];
const passed = (name) => { checks.push(name); console.log(`PASS: ${name}`); };
const artifacts = artifactsDirectory;
try {
  await fs.mkdir(artifacts, { recursive: true });
  database = await MongoMemoryReplSet.create({ replSet: { count: 1 }, binary: { version: "7.0.14" } });
  await mongoose.connect(database.getUri("qa_smoke"));
  await initializeDatabase();
  const password = "Qa-password-2026";
  const passwordHash = await hashPassword(password);
  const [admin, manager, tech] = await User.insertMany([
    ["admin", "QA Admin", "ADMIN"], ["manager", "QA Manager", "MANAGER"], ["tech", "QA Technician", "EMPLOYEE"],
  ].map(([name, fullName, role]) => ({ email: `${name}@qa.test`, fullName, role, branchId: "LOCAL-WAREHOUSE", passwordHash })));
  const web = express();
  web.use((req, res, next) => req.path.startsWith("/api/") ? app(req, res, next) : next());
  web.use(express.static(frontendBuild));
  web.get("*", (req, res) => res.sendFile(path.join(frontendBuild, "index.html")));
  server = await new Promise(resolve => { const listener = web.listen(0, "127.0.0.1", () => resolve(listener)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
  const errors = [];
  async function login(user) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.route("**/api/brands/*/logo", route => route.fulfill({ json: { logoUrl: null, sourceUrl: null } }));
    const currentPage = await context.newPage();
    currentPage.setDefaultTimeout(12000);
    currentPage.on("pageerror", error => errors.push(error.message));
    currentPage.on("response", response => { if (response.url().includes("/api/") && response.status() >= 500) errors.push(`HTTP ${response.status()}: ${new URL(response.url()).pathname}`); });
    await currentPage.goto(base);
    await currentPage.getByLabel("Email", { exact: true }).fill(user.email);
    await currentPage.getByLabel("Password", { exact: true }).fill(password);
    await currentPage.getByRole("button", { name: "Sign In", exact: true }).click();
    await currentPage.getByRole("button", { name: "Inventory Catalog", exact: true }).waitFor();
    const token = await currentPage.evaluate(() => sessionStorage.getItem("ashcol_inventory_token"));
    const request = (method, endpoint, data) => context.request.fetch(`${base}/api${endpoint}`, { method, headers: { Authorization: `Bearer ${token}` }, data });
    return { page: currentPage, request };
  }
  const administrator = await login(admin);
  page = administrator.page;
  const nav = name => page.getByRole("button", { name, exact: true }).first().click();
  async function choose(combo, text) {
    await combo.click();
    await page.locator(".ant-select-dropdown:visible .ant-select-item-option").filter({ hasText: text }).first().click();
  }
  async function numeric(input, value, decimals = false) {
    await input.fill(value);
    await input.press("End");
    const before = await input.inputValue();
    await input.pressSequentially("abc-e+");
    assert.equal(await input.inputValue(), before, "Numeric fields must reject letters/signs");
    const rejected = await input.evaluate(node => {
      const clipboardData = new DataTransfer(); clipboardData.setData("text/plain", "bad123");
      return !node.dispatchEvent(new ClipboardEvent("paste", { bubbles: true, cancelable: true, clipboardData }));
    });
    assert.equal(rejected, true, "Invalid paste must be blocked");
    if (!decimals) { await input.press("."); assert.equal(await input.inputValue(), before); }
  }
  await nav("Suppliers & Vendors");
  await page.getByRole("button", { name: "Register Supplier", exact: true }).click();
  let dialog = page.getByRole("dialog");
  await dialog.getByLabel("Company / Supplier Name *", { exact: true }).fill("QA Supply");
  await dialog.getByLabel("Phone Number", { exact: true }).fill("abc09171234567xyz");
  assert.equal(await dialog.getByLabel("Phone Number", { exact: true }).inputValue(), "09171234567");
  await dialog.getByLabel("Email Address", { exact: true }).fill("qa@g");
  await dialog.getByLabel("Email Address", { exact: true }).press("Tab");
  assert.equal(await dialog.getByLabel("Email Address", { exact: true }).inputValue(), "qa@gmail.com");
  await dialog.getByRole("button", { name: "Register Supplier", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.getByRole("cell", { name: "QA Supply", exact: true }).waitFor();
  const supplier = await Supplier.findOne({ name: "QA Supply" });
  assert.ok(supplier);
  await page.getByTitle("Archive Supplier", { exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Archive Supplier", exact: true }).click();
  await page.getByRole("cell", { name: "QA Supply", exact: true }).waitFor({ state: "hidden" });
  assert.equal((await Supplier.findById(supplier._id)).archived, true);
  await page.getByRole("button", { name: "View Archives", exact: true }).click();
  await page.getByRole("cell", { name: "QA Supply", exact: true }).waitFor();
  await page.getByTitle("Restore Supplier", { exact: true }).click();
  await page.getByRole("cell", { name: "QA Supply", exact: true }).waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "View Active Suppliers", exact: true }).click();
  await page.getByRole("cell", { name: "QA Supply", exact: true }).waitFor();
  assert.equal((await Supplier.findById(supplier._id)).phone, "09171234567");
  passed("Supplier creation, phone filtering, email completion, archive and restore preserve details");
  await page.getByRole("button", { name: "Show Brands", exact: true }).click();
  await page.getByLabel("New brand name").fill("QA Brand");
  await page.getByRole("button", { name: "Add Brand", exact: true }).click();
  await page.getByRole("button", { name: "Remove QA Brand", exact: true }).waitFor();
  assert.ok(await page.getByRole("button", { name: "Hide Brands", exact: true }).isVisible());
  await page.getByRole("button", { name: "Remove QA Brand", exact: true }).click();
  await page.getByRole("button", { name: "Remove QA Brand", exact: true }).waitFor({ state: "hidden" });
  passed("Brand add/remove keeps the expanded panel open");
  await nav("Inventory Catalog");
  async function register(sku, quantity, unit = "PCS") {
    await page.getByRole("button", { name: "Register Item", exact: true }).click();
    const form = page.getByRole("dialog");
    assert.equal(await form.getByLabel("SKU / model", { exact: true }).evaluate(node => node.validity.valueMissing), true);
    await form.getByLabel("SKU / model", { exact: true }).fill(sku);
    await form.getByLabel("Item name", { exact: true }).fill(sku === "QA-ZERO" ? "QA empty item" : "QA copper connector");
    await choose(form.getByRole("combobox", { name: "Item type", exact: true }), "Material / Part");
    await choose(form.getByRole("combobox", { name: "Unit of measure", exact: true }), unit);
    await numeric(form.getByRole("spinbutton", { name: "Opening quantity", exact: true }), quantity, unit === "METER");
    await numeric(form.getByRole("spinbutton", { name: "Unit cost (PHP)", exact: true }), "12.25", true);
    await numeric(form.getByRole("spinbutton", { name: "Selling price (PHP)", exact: true }), "20.50", true);
    await numeric(form.getByRole("spinbutton", { name: "Reorder level", exact: true }), "0", unit === "METER");
    await form.getByRole("button", { name: "Save item", exact: true }).click();
    return form;
  }
  dialog = await register("QA-PIPE", "5");
  await dialog.waitFor({ state: "hidden" });
  await page.getByRole("cell", { name: "QA-PIPE", exact: true }).waitFor();
  const product = await Product.findOne({ sku: "QA-PIPE" });
  assert.equal(product.quantity, 5); assert.equal(product.unitCost, 12.25); assert.equal(product.reorderLevel, 0);
  passed("Item registration rejects letters/signs/invalid paste and preserves decimal prices and zero reorder level");
  dialog = await register("QA-PIPE", "1");
  await dialog.getByRole("alert").waitFor();
  assert.equal(await Product.countDocuments({ sku: "QA-PIPE" }), 1);
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  dialog = await register("QA-ZERO", "0");
  await dialog.waitFor({ state: "hidden" });
  let row = page.getByRole("row").filter({ hasText: "QA-ZERO" });
  await row.getByRole("button", { name: "Archive item", exact: true }).click();
  await page.getByRole("button", { name: "OK", exact: true }).click();
  await row.waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "View archived zero-stock items", exact: true }).click();
  row = page.getByRole("row").filter({ hasText: "QA-ZERO" });
  await row.getByRole("button", { name: "Restore item", exact: true }).click();
  await page.getByRole("button", { name: "OK", exact: true }).click();
  await row.waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "View active catalog items", exact: true }).click();
  await page.getByRole("row").filter({ hasText: "QA-ZERO" }).waitFor();
  const nonzero = await administrator.request("DELETE", `/products/${product.id}`);
  assert.equal(nonzero.status(), 409);
  passed("Duplicate SKU is rejected; zero stock archives/restores; nonzero stock cannot be archived");
  dialog = await register("QA-METER", "1.125", "METER");
  await dialog.waitFor({ state: "hidden" });
  const measured = await Product.findOne({ sku: "QA-METER" });
  assert.equal(measured.quantity, 1.125);
  passed("Measured materials retain three-decimal opening quantities");
  await nav("Post Movement");
  await page.getByLabel("Select an Item", { exact: true }).selectOption(product.id);
  await numeric(page.getByRole("spinbutton", { name: "Quantity", exact: true }), "2");
  await page.getByLabel("Receipt, transfer reference, or explanation").fill("QA delivery");
  const ticket = await page.getByLabel("Transaction ID").inputValue();
  assert.match(ticket, /^STI - \d{4,}$/);
  await page.getByRole("button", { name: "Confirm & Post", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Yes, Confirm & Post", exact: true }).click();
  await page.getByRole("dialog").waitFor({ state: "hidden" });
  assert.equal((await Product.findById(product._id)).quantity, 7);
  await page.locator("label").filter({
    has: page.getByRole("radio", { name: "Stock Out", exact: true }),
  }).click();
  await page.getByLabel("Select an Item", { exact: true }).selectOption(product.id);
  await page.getByRole("spinbutton", { name: "Quantity", exact: true }).fill("1");
  await page.getByLabel("Receipt, transfer reference, or explanation").fill("QA stock issue");
  await page.waitForFunction(() => /^STO - \d{4,}$/.test(document.querySelector('#pm-transaction-id')?.value || ""));
  await page.getByRole("button", { name: "Confirm & Post", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Yes, Confirm & Post", exact: true }).click();
  await page.getByRole("dialog").waitFor({ state: "hidden" });
  assert.equal((await Product.findById(product._id)).quantity, 6);
  passed("Stock In/Out posting, operation switching, numeric controls and STI/STO references reconcile");
  await nav("Service Vehicles");
  await page.getByRole("button", { name: "Add Vehicles", exact: true }).click();
  dialog = page.getByRole("dialog");
  await dialog.getByRole("textbox", { name: "Vehicle name", exact: true }).fill("QA Service Vehicle");
  await choose(dialog.getByRole("combobox", { name: "New vehicle type", exact: true }), "Pickup");
  await choose(dialog.getByRole("combobox", { name: "New vehicle driver", exact: true }), "QA Technician");
  await dialog.getByRole("button", { name: "Register Vehicle", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  const van = await ServiceVan.findOne({ name: "QA Service Vehicle" });
  assert.equal(van.driverId, String(tech._id));
  await nav("Inventory Catalog");
  row = page.getByRole("row").filter({ hasText: "QA-PIPE" });
  await row.getByRole("button", { name: "Add to Service Vehicle", exact: true }).click();
  dialog = page.getByRole("dialog");
  await numeric(dialog.getByRole("spinbutton", { name: "Quantity to load", exact: true }), "2");
  await dialog.getByRole("button", { name: "Confirm Load to Van", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  assert.equal((await Product.findById(product._id)).quantity, 4);
  passed("Vehicle registration/technician assignment and warehouse loadout reconcile");
  const technician = await login(tech);
  await technician.page.getByRole("button", { name: "Inventory Catalog", exact: true }).click();
  assert.equal(await technician.page.getByRole("button", { name: "Register Item", exact: true }).count(), 0);
  assert.equal((await technician.request("DELETE", `/suppliers/${supplier.id}`)).status(), 403);
  assert.equal((await technician.request("POST", "/brands", { name: "Forbidden" })).status(), 403);
  assert.equal((await technician.request("DELETE", `/products/${product.id}`)).status(), 403);
  const managerSession = await login(manager);
  assert.equal((await managerSession.request("POST", "/service-vans", { id: "FORBIDDEN" })).status(), 403);
  assert.equal((await managerSession.request("DELETE", `/users/${tech.id}`)).status(), 403);
  passed("Technician and manager permissions are enforced in both UI and API");
  await nav("Service Vehicles");
  await page.getByTitle("View vehicle details").click();
  row = page.getByRole("row").filter({ hasText: "QA-PIPE" });
  await row.getByRole("button", { name: "Unload to Branch", exact: true }).click();
  dialog = page.getByRole("dialog");
  await numeric(dialog.getByRole("spinbutton", { name: "Quantity to return", exact: true }), "1");
  await dialog.getByRole("button", { name: "Confirm Return", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  assert.equal((await Product.findById(product._id)).quantity, 5);
  assert.equal((await Product.findOne({ branchId: van.id, sku: product.sku })).quantity, 1);
  await nav("Stock Ledger");
  await page.getByPlaceholder("Search SKU, item, or reference").fill("QA-PIPE");
  await page.getByText("Returned", { exact: true }).first().waitFor();
  const numbered = await Movement.find({ sku: "QA-PIPE", transferNumber: { $exists: true } }).lean();
  assert.equal(numbered.length, 4);
  for (const movement of numbered) assert.match(movement.transferNumber, /^(TRI|TRO)\d{4,}$/);
  assert.equal(numbered.filter(entry => entry.isVehicleReturn).length, 2);
  passed("Vehicle returns show Returned, retain TRI/TRO references, and balance both locations");
  await page.reload();
  await page.getByRole("heading", { name: "Inventory Transaction History", exact: true }).waitFor();
  passed("Page refresh preserves the current Stock Ledger page");
  await nav("Overview");
  await page.getByRole("heading", { name: "Overview", exact: true }).waitFor();
  await page.screenshot({ path: path.join(artifacts, "overview-desktop.png"), fullPage: true });
  await page.getByRole("button", { name: /QA Admin/ }).click();
  await page.getByRole("menuitem", { name: "Switch to Dark Mode", exact: true }).click();
  assert.equal(await page.evaluate(() => localStorage.getItem("ashcol_theme")), "dark");
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(artifacts, "overview-mobile.png"), fullPage: true });
  passed("Overview remains usable in dark mode and at phone width without page overflow");
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(artifacts, "qa-smoke-results.json"), JSON.stringify({ checks, browserErrors: errors }, null, 2));
  console.log(`QA complete: ${checks.length} workflow groups passed; no browser exceptions or server errors.`);
} catch (error) {
  if (page) {
    await page.screenshot({ path: path.join(artifacts, "failure.png"), fullPage: true }).catch(() => {});
    console.error((await page.locator("body").innerText()).slice(-3500));
  }
  throw error;
} finally {
  await browser?.close();
  if (server) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
  await mongoose.disconnect();
  await database?.stop();
}
